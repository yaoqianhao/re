//! 退出码常量。
//!
//! # 为什么单独一个文件
//!
//! 这几个数字是 `r3e-cli` 对外契约的一部分（`docs/M1_S5_PLAN.md` §3.3），
//! 也被 `tools/agent_smoke.py` 与 Gate 1 的断言直接引用。散在各处写 `2`、`3`
//! 迟早会出现「这里加了个参数错误却回了 1」，所以集中定义、只在这层定义。

/// 成功（`verify` 通过也走这个）。
pub const OK: i32 = 0;

/// 业务否定：命令跑通了，引擎明确说了「不行」。
///
/// 典型：`verify` 的 `passed=false`、`tx.apply` 被 `TX_REJECTED`。
/// 与 3 的区别是「环境是好的，是要求被拒了」——脚本据此决定是改场景还是修环境。
pub const NEGATIVE: i32 = 1;

/// 用法或参数错误：命令本身就没拼对，不值得连引擎。
pub const USAGE: i32 = 2;

/// 环境错误：连不上 / 鉴权失败 / 超时 / 引擎过载。
pub const ENV: i32 = 3;

/// 依赖缺失：`replay` 找不到 `r3e-replay` 二进制。
///
/// 单独一个码而不是并进 3：环境错误重试可能有用，缺二进制重试一万次也没用。
pub const MISSING_DEP: i32 = 4;
